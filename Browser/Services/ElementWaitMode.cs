// =============================================================================
// ElementWaitMode.cs — режимы ожидания элементов
//
// Определяет различные стратегии ожидания элементов на странице.
// Используется для унификации логики ожидания во всех элементных активностях.
// =============================================================================

namespace Primo.MIA
{
    /// <summary>
    /// Режимы ожидания элементов на странице.
    /// </summary>
    public enum ElementWaitMode
    {
        /// <summary>
        /// Ожидать только появления элемента в DOM (может быть невидимым).
        /// </summary>
        Present,

        /// <summary>
        /// Ожидать пока элемент станет видимым (Displayed = true).
        /// </summary>
        Visible,

        /// <summary>
        /// Ожидать пока элемент станет кликабельным (Displayed = true и Enabled = true).
        /// </summary>
        Clickable,

        /// <summary>
        /// Не ожидать - попытаться найти элемент немедленно.
        /// </summary>
        None
    }
}