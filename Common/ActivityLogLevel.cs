// =============================================================================
// ActivityLogLevel.cs — уровень детализации общего лога активностей MIA.
//
// Управляется активностью «Лог: Настройки» (Utilities) или переменной
// окружения PRIMO_MIA_LOG_LEVEL (debug/info/none). Значение хранится в
// статике ActivityFileLogger — как и весь файловый логгер, рассчитано на
// «один робот на процесс» (ограничение Primo Studio).
// =============================================================================

namespace Primo.MIA
{
    /// <summary>
    /// Уровень логирования активностей MIA.
    /// Порядок значений = строгость фильтра: в лог попадают сообщения
    /// с рангом НЕ НИЖЕ выбранного уровня (Debug &lt; Info &lt; None).
    /// </summary>
    public enum ActivityLogLevel
    {
        /// <summary>Максимум диагностики: Debug + Info + Warn + Error.
        /// Для отладки сценариев: параметры запросов, критерии поиска,
        /// размеры данных, решения ack/nack, тайминги.</summary>
        [RuName("Debug")]
        Debug = 0,

        /// <summary>Только ключевые события: Info + Warn + Error.
        /// Значение по умолчанию — запуск/завершение операций, счётчики
        /// результатов, предупреждения о частичных сбоях.</summary>
        [RuName("Info")]
        Info = 1,

        /// <summary>Логирование выключено (включая Warn/Error — ошибки
        /// всё равно попадают в консоль Studio через ExecutionException).</summary>
        [RuName("None")]
        None = 2
    }
}
